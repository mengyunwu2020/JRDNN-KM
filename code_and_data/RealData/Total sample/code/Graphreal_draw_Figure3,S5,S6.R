current_file <- here("RealData", "Total Sample","result_data", "Result_ground_truth")


dataset_folders <- c("luad", "pbmc", "mescs", "mouse liver", "mouse uterus")
datasets        <- c("LUAD", "PBMC", "mESCs", "Mouse Liver", "Mouse Uterus")


networks <- c("CORUM", "PPI(F)", "PPI(P)", "PerturbAtlas") 
