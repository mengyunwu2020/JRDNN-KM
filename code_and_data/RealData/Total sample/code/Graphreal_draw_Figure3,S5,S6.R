plot_metric_array <- function(metric_array, metric_name) {
  mean_metric <- apply(metric_array, c(1, 3), mean)  
  
  
  
  n_col <- length(datasets)
  layout_matrix <- matrix(c(1:n_col, rep(n_col+1, n_col)), 
                          nrow = 2, byrow = TRUE)
  layout(layout_matrix, heights = c(0.55, 0.45))  
  
  
  par(oma = c(3, 3, 0, 1),  
      mar = c(2, 5, 1.5, 1)) 
  
  method_pch <- c(15, 16, 17, 18, 0, 1, 2, 5, 8)
  net_colors <- c("#E41A1C", "#377EB8", "#4DAF4A", "#984EA3")
  
  
  if (metric_name=='F1 Score'){
    y_max=0.8
  } else if (metric_name=='Recall'){
    y_max=0.9
  } else 
  {y_max=0.9
  
  }
  
  
  for (i in seq_along(datasets)) {
    plot_data <- as.data.frame.table(metric_array[,, datasets[i]])
    colnames(plot_data) <- c("Method", "Network", "F1")
    
    plot(1, type = "n", xlim = c(0.5, 9.5), ylim = c(0, y_max),
         xlab = "", ylab = ifelse(i == 1, metric_name, ""),  
         xaxt = "n", main = datasets[i],cex.main = 1.5,   
         cex.lab = 1.5,cex.axis = 1.4)
    
    abline(h = seq(0.2, 0.8, by = 0.2), col = "gray90", lty = 3)
    
    for (net in seq_along(networks)) {
      subset_data <- plot_data[plot_data$Network == networks[net], ]
      points(x = as.numeric(subset_data$Method), 
             y = subset_data$F1,
             pch = method_pch,
             col = net_colors[net],
             cex = 1.2)
    }
    
    
    for (j in seq_along(methods)) {
      mean_value <-mean_metric[j, i]
      segments(x0 = j - 0.4, 
               x1 = j + 0.4,
               y0 = mean_value, 
               y1 = mean_value,
               col = "red", lwd = 3, lty = 1)
    }
    
    axis(1, at = 1:9, labels = methods, las = 2, cex.axis = 1)
  }
  
  
  
  plot(1, type = "n", axes = FALSE, xlab = "", ylab = "")
  legend("top", 
         legend = c("Network Types:", networks, "Mean (red line)"),
         col = c(NA, net_colors, "red"),
         pch = c(NA, rep(15, 4), NA),
         lty = c(NA, rep(NA, 4), 1),
         lwd = c(NA, rep(NA, 4), 3),
         title = NULL,
         bty = "n", 
         cex = 1.1,
         horiz = TRUE,
         xpd = NA,
         x.intersp = 0.3,            
         y.intersp = 0.8,              
         text.width = NULL,           
         seg.len = 1.5,
         inset = c(0, 0.15)
  )
  
  
}


plot_metric_array(f1_array,        "F1 Score")
plot_metric_array(recall_array,    "Recall")
plot_metric_array(precision_array, "Precision")
