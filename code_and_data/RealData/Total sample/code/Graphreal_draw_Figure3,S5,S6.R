safe_numeric <- function(x) {
  if (is.factor(x)) x <- as.character(x)
  if (is.character(x)) {
    x <- trimws(x)
    x[x %in% c("", "NA", "NaN")] <- NA_character_
  }
  suppressWarnings(as.numeric(x))
}

pull_metric <- function(path, metric) {
  if (!file.exists(path)) return(NULL)
  df <- tryCatch(read.xlsx(path), error = function(e) NULL)
  if (is.null(df)) return(NULL)
  cn <- tolower(colnames(df))
  method_col <- which(cn == "method")
  metric_col <- which(cn == tolower(metric))
  if (!length(method_col) || !length(metric_col)) return(NULL)
  m <- as.character(df[[method_col[1]]])
  v <- safe_numeric(df[[metric_col[1]]])
  names(v) <- m
  v[is.finite(v)]
}


build_array <- function(metric) {
  arr <- array(NA_real_,
               dim = c(length(methods), length(networks), length(datasets)),
               dimnames = list(methods, networks, datasets))
  for (k in seq_along(dataset_folders)) {
    fold <- dataset_folders[k]
    for (j in seq_along(network_files)) {
      # file.path works perfectly combined with the path string generated by here()
      p <- file.path(current_file, fold, network_files[j])
      v <- pull_metric(p, metric)
      if (length(v)) {
        common <- intersect(names(v), methods)
        arr[common, names(network_files)[j], datasets[k]] <- v[common]
      }
    }
  }
  arr
}


f1_array        <- build_array("F1")
recall_array    <- build_array("Recall")
precision_array <- build_array("Precision")

